// The MEIDNet Matter mark, a sibling of MEIDNet Prism's: target-property streams enter Prism's glass octahedron, and a
// soft spectrum leaves it into a glass cubic unit cell, the crystal structure. This script writes the two files that
// carry it:
//   frontend/public/favicon.svg                          the browser-tab icon (with a simpler drawing at 16-24 px)
//   frontend/src/components/brand/MatterMark.tsx         the header and footer mark, inlined
// usage (from the repository root):  node scripts/brand/matter_mark.mjs
// The geometry lives in matter_mark_gen.mjs (Prism's facet plan, measured on Prism's 512 px mark). The full logo for
// the social preview (frontend/public/og.png) comes from matter_lockup.mjs: it writes a 1200x630 page, which is then
// captured with a headless browser (the wordmark uses Segoe UI, so capture it on Windows).
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from './matter_mark_gen.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

export const FINAL = {
  hx: 0.86, h: 48, top: 8, cx: 19.5,                 // the octahedron: toward Prism's proportions, filling the height
  cubeA: 7.3, cubeC: [52, 32.4], beamEnd: 45, beamSpread: 8.3,
  frontOp: 0.5, topOp: 0.6,                          // the unit cell as glass, like the gem
  bandBlur: 0.6,                                     // a soft spectrum, like Prism's beam
};

writeFileSync(resolve(ROOT, 'frontend/public/favicon.svg'), build({ ...FINAL, prefix: 'mmf-' }).svg);

// the inline mark: no <style> (its media query serves the 16 px favicon), only the children of <svg>
const inline = build({ ...FINAL, prefix: 'mm-', small: 0 }).svg;
const inner = inline.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
if (/<style|<svg/.test(inner)) throw new Error('unexpected markup in the inline mark');

const tsx = `import { useId } from 'react';

/** The Matter mark, a sibling of MEIDNet Prism's: target-property streams enter Prism's glass octahedron, and a soft
 *  spectrum leaves it into a glass cubic unit cell, the crystal structure. Generated by scripts/brand/matter_mark.mjs
 *  (do not edit the markup by hand). It is inlined, so the header needs no extra request, and every id gets a prefix
 *  unique to the instance, because the page draws the mark twice (header and footer). */
const MARK = ${JSON.stringify(inner)};

export function MatterMark({ size = 28 }: { size?: number }) {
  const prefix = 'mm' + useId().replace(/[^a-zA-Z0-9_-]/g, '') + '-';
  return <svg width={size} height={size} viewBox="0 0 64 64" role="img" aria-label="MEIDNet Matter" dangerouslySetInnerHTML={{ __html: MARK.replaceAll('mm-', prefix) }} />;
}

export function Wordmark({ sub = 'Matter' }: { sub?: string }) {
  return <><b>MEIDNet</b>&nbsp;<span>{sub}</span></>;
}
`;
writeFileSync(resolve(ROOT, 'frontend/src/components/brand/MatterMark.tsx'), tsx);
console.log('wrote frontend/public/favicon.svg and frontend/src/components/brand/MatterMark.tsx');
